-- PostgreSQL 15+ (production uses 16). Collapse identical current quotes only.
-- NULL lines are part of the key for 1X2, BTTS and double chance.
LOCK TABLE match_odds IN SHARE ROW EXCLUSIVE MODE;
WITH duplicates AS (
    SELECT id, row_number() OVER (
        PARTITION BY match_id, bookmaker, market, line, selection, snapshot_type, price
        ORDER BY provider_updated_at DESC NULLS LAST, recorded_at DESC NULLS LAST, id DESC
    ) AS duplicate_number
    FROM match_odds
    WHERE snapshot_type = 'pre_match'
)
DELETE FROM match_odds AS current_odds
USING duplicates
WHERE current_odds.id = duplicates.id AND duplicates.duplicate_number > 1;
CREATE UNIQUE INDEX IF NOT EXISTS uq_current_prematch_odds
ON match_odds (match_id, bookmaker, market, line, selection, snapshot_type)
NULLS NOT DISTINCT WHERE snapshot_type = 'pre_match';

CREATE TABLE IF NOT EXISTS corner_observations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id integer NOT NULL REFERENCES matches(id),
    provider_response_id integer NOT NULL UNIQUE REFERENCES provider_responses(id),
    total integer NOT NULL CONSTRAINT ck_corner_observation_total CHECK (total >= 0)
);
CREATE INDEX IF NOT EXISTS ix_corner_observations_match_id ON corner_observations(match_id);

CREATE OR REPLACE FUNCTION prevent_historical_rewrite() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Historical table % is append-only (% rejected)', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END
$$;

DO $$
DECLARE
    historical_table text;
BEGIN
    FOREACH historical_table IN ARRAY ARRAY[
        'prediction_snapshots', 'match_odds_history', 'provider_responses',
        'standings_snapshots', 'team_match_features', 'corner_observations'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS historical_append_only ON %I', historical_table);
        EXECUTE format(
            'CREATE TRIGGER historical_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON %I
             FOR EACH STATEMENT EXECUTE FUNCTION prevent_historical_rewrite()', historical_table
        );
    END LOOP;
END
$$;
COMMIT;
